/* SESSION-CORE-001: the session's private side. Only the .c files of native/session and
 * native/session/domains include this (scripts/audit_includes.py fails `make test` otherwise).
 *
 * Layout of the core:
 *   session.c          lifecycle, pump loop, barrier, submit routing, revisions, status, world port
 *   cues.c             the cue ring
 *   lease.c            the simulation lease and its audit (MU_SESSION_AUDIT)
 *   journal.c          the journal writer and reader (mu_journal.h)
 *   dispatch.c         THE dispatcher, generated from the ops files joined with the route table
 *   seed.c             mu_session_open_seeded (MU_SESSION_SEED builds only)
 *   domains/<d>.c      per-domain state, apply functions, submit functions, env adapters
 *   domains/<d>.h      per-domain PUBLIC view types and getters (included by session_domains.h)
 *   domains/<d>_state.h  per-domain PRIVATE state struct (embedded in struct mu_session)
 *   domains/<d>.intents  per-domain intent kinds (generated into session_intents.h)
 *   ops/<d>.ops        per-domain dispatcher rows and intent routes (X-macro)
 *
 * build/gen/{session_domains.h, domains_all.def, session_domains_state.h, ops_all.def, routes.def,
 * bound_routes.def, session_intents.h} are generated by scripts/gen_domains.py from the files
 * present (sorted), so adding a domain or an opcode never edits a shared list. Two rows for one
 * (opcode, sub) are refused by the generator and, past it, become duplicate `case` labels in
 * dispatch.c that do not compile.
 */
#ifndef MU_SESSION_INTERNAL_H
#define MU_SESSION_INTERNAL_H

#include "mu_session.h"
#include "mu_journal.h"
#include "mu_session_tools.h"
#include "../net/mu_conn.h"

/* ---- dispatcher rows ---------------------------------------------------------------------
 *
 * In the route table (native/net/dispatch.def, else dispatch.seed.def; copied to routes.def):
 *   MU_FAMILY(opcode, sub_at_c1, sub_at_c2, client_subdispatch)
 *       the opcode is sub-dispatched by one byte, read where the client's own sub-dispatcher reads
 *       it for a 1-byte-size head (C1/C3) and a 2-byte-size head (C2/C4). MU_AT_UNKNOWN: that head
 *       is not recovered for this family; such a frame is journaled as unbound, never guessed.
 *   MU_ROUTE(opcode, sub, client_handler, evidence)   sub = MU_SUB_NONE without a family row
 * In native/session/ops/<domain>.ops (hand-written, one file per domain):
 *   MU_OP(opcode, sub, apply_fn)          binds a native apply function to one route
 *   MU_SUBMIT(intent_kind, submit_fn)     the domain that turns this intent kind into requests
 */
#define MU_SUB_NONE 0x100u
#define MU_SUB_SHORT 0x101u      /* the frame is too short to carry its sub byte */
#define MU_SUB_HEAD 0x102u       /* the family's sub offset for this head is MU_AT_UNKNOWN */
#define MU_AT_UNKNOWN 0xffffu
#define MU_ADDR_UNVERIFIED 0u    /* a route whose client handler address is not recovered yet */
#define MU_OP_KEY(op, sub) (((uint32_t)(op) << 9) | (uint32_t)(sub))

typedef enum mu_apply {
    MU_APPLY_DONE = 0,           /* state written (revisions bumped by the apply function) */
    MU_APPLY_IGNORED,            /* the client's handler ignores it (or the route is unbound / ignored) */
    MU_APPLY_WORLD_CHANGE        /* applied; the world changes: stop applying until attach_world(world) */
} mu_apply;

typedef mu_apply (*mu_apply_fn)(mu_session *s, const mu_frame *f);
typedef mu_submit (*mu_submit_fn)(mu_session *s, const mu_intent *in);

/* ---- the cue ring ------------------------------------------------------------------------- */
#define MU_CUE_RING 1024
typedef struct mu_cue_ring {
    mu_cue ring[MU_CUE_RING];
    uint64_t next_seq;           /* seq of the next cue written; ring[seq % MU_CUE_RING] */
} mu_cue_ring;

/* ---- lease audit zones -------------------------------------------------------------------- */
typedef enum mu_zone { MU_ZONE_REPLICATED = 0, MU_ZONE_MOTION, MU_ZONE_VIEW } mu_zone;
typedef struct mu_audit_zone {
    const char *name;            /* "hero.record" */
    const uint8_t *base;         /* the record */
    uint32_t offset, size;       /* the zone inside it */
    mu_zone zone;
    const char *field;           /* what lives there, for the abort message */
} mu_audit_zone;
#define MU_AUDIT_ZONES_MAX 256
typedef struct mu_audit_zones {
    mu_audit_zone z[MU_AUDIT_ZONES_MAX];
    int count;
} mu_audit_zones;
void mu_audit_add(mu_audit_zones *zs, const char *name, const uint8_t *base, uint32_t offset, uint32_t size, mu_zone zone,
                  const char *field);

#include "layout_types.h"
void mu_audit_layout(mu_audit_zones *zs, const char *name, const uint8_t *base, uint32_t size,
                     const mu_layout_record *record);

struct mu_session_seed;

/* Domain state structs and the generated domain list: one row per domains/<name>_state.h */
#include "session_domains_state.h"

/* Every domain provides these (missing ones fail to link): */
#define MU_DOMAIN(name)                                                                \
    void mu_dom_##name##_init(mu_session *s);                                          \
    void mu_dom_##name##_free(mu_session *s);                                          \
    void mu_dom_##name##_zones(const mu_session *s, mu_audit_zones *zones);            \
    void mu_dom_##name##_step(mu_session *s, const mu_sim *sim);                       \
    void mu_dom_##name##_seed(mu_session *s, const struct mu_session_seed *seed);
#include "domains_all.def"
#undef MU_DOMAIN

typedef struct mu_route_info {
    uint8_t head, opcode;
    uint16_t sub;
    uint32_t client_handler;
    const char *apply;           /* NULL: unbound */
} mu_route_info;

struct mu_session {
    mu_session_config cfg;
    const mu_client_build *build;
    mu_net net;
    mu_phase phase;
    mu_close_reason reason;
    int32_t reason_code;
    uint32_t now, tick;
    int pumping;                 /* submit refuses while set */
    mu_conn_kind conn_main;      /* the connection requests go to (game once hopped / seeded) */

    mu_place place;

    /* world attachment and barrier */
    mu_world_port port;
    int has_port;
    int32_t waiting_world;       /* -1 none */

    /* lease */
    uint32_t sim_epoch;
    int sim_open;
    uint8_t *audit_snapshot;     /* MU_SESSION_AUDIT: the replicated zones at sim_begin */
    size_t audit_size;

    /* outputs */
    uint32_t rev[MU_DOMAIN_COUNT];
    mu_cue_ring cues;
    uint32_t frames_in, frames_out, unhandled, undecodable, unsent;
    mu_route_info route;         /* the route of the frame being applied (journal) */
    uint64_t cues_at_frame;
    mu_frame frame;              /* scratch for the pump */

    /* one field per domain, generated: mu_dom_hero hero; ... */
#define MU_DOMAIN(name) mu_dom_##name name;
#include "domains_all.def"
#undef MU_DOMAIN
};

/* ---- services for domain files ----------------------------------------------------------- */

/* Bump a domain's revision (call once per apply that changed it). */
void mu_session_touch(mu_session *s, mu_domain d);
/* Append a cue (seq assigned here). */
void mu_session_cue(mu_session *s, const mu_cue *cue);
/* Send a request on the session's main connection: mu_net_send plus the journal. `encrypted` is
 * Send 0x00d51d4f's first argument (1: the C3/C4 wrap). Returns a mu_send_status. */
int mu_session_send(mu_session *s, mu_packet *p, int encrypted);
/* Phase transitions are only made through this (journaled). */
void mu_session_set_phase(mu_session *s, mu_phase phase);
/* A server placement (journaled; place.seq increases). */
void mu_session_set_place(mu_session *s, const mu_place *place);
/* Terminal close with a reason (journaled; links closed). */
void mu_session_fail(mu_session *s, mu_close_reason reason, int32_t code);
/* The hero's live motion through the port (the no-world answer without one). */
void mu_session_hero_motion(const mu_session *s, int32_t tile[2], float position[3], float angle[3]);
/* An unfinished request body: journal it, return MU_SUBMIT_UNRECOVERED. */
mu_submit mu_session_unrecovered(mu_session *s, const mu_intent *in, const char *what);
/* GlobalText through cfg.lang ("" without one). */
const char *mu_session_global_text(const mu_session *s, int32_t index);
/* Every domain's audit zones (lease audit, journal snapshots). */
void mu_session_zones(const mu_session *s, mu_audit_zones *zones);

/* journal writers (journal.c); every one is a no-op on NULL */
void mu_journal_start(mu_journal *j, const char *build_sha256_hex);
void mu_journal_text(mu_journal *j, uint8_t type, uint32_t tick, uint32_t ms, const char *text);
void mu_journal_frame_in(mu_journal *j, uint32_t tick, uint32_t ms, const mu_frame *f, mu_decode_status ds,
                         const mu_route_info *route, int apply_result, int held, uint32_t cues);
void mu_journal_frame_out(mu_journal *j, uint32_t tick, uint32_t ms, mu_conn_kind conn, const uint8_t *frame,
                          size_t size, int send_status, int encrypted);
void mu_journal_intent(mu_journal *j, uint32_t tick, uint32_t ms, uint32_t kind, int32_t status, int32_t notice);
void mu_journal_snapshot(mu_journal *j, uint32_t tick, uint32_t ms, const mu_audit_zones *zones);
int mu_journal_wants_snapshot(const mu_journal *j, uint32_t tick);
void mu_journal_count_cues(mu_journal *j, uint64_t cues);
void mu_journal_set_ticks(mu_journal *j, uint32_t ticks);
/* records made between these two (an apply's sends, events) are written after the frame's own record */
void mu_journal_begin_frame(mu_journal *j);
void mu_journal_end_frame(mu_journal *j);

/* dispatch.c (the row table itself: mu_session_tools.h) */
mu_apply mu_session_dispatch(mu_session *s, const mu_frame *f);
extern const mu_submit_fn mu_session_submit_routes[MU_INTENT_KINDS];
extern const char *const mu_session_submit_names[MU_INTENT_KINDS];

#endif /* MU_SESSION_INTERNAL_H */

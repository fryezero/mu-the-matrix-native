/* SESSION-CORE-001 (sketch): the session's private side. Only native/session/*.c and
 * native/session/domains/*.c include this (scripts/audit_includes.py; a view that includes it
 * fails `make test`).
 *
 * Layout of the core:
 *   session.c          lifecycle, pump loop, barrier, submit routing, revisions, cue ring, lease
 *   dispatch.c         THE dispatcher, generated from ops/*.ops (the client's 0x01287ead table)
 *   domains/<d>.c      per-domain state, apply functions, submit functions, env adapters
 *   domains/<d>.h      per-domain PUBLIC view types and getters (included by session_domains.h)
 *   domains/<d>_state.h  per-domain PRIVATE state struct (embedded in struct mu_session)
 *   ops/<d>.ops        per-domain dispatcher rows and intent routes (X-macro)
 *
 * build/gen/session_domains.h and build/gen/ops_all.def are generated by
 * native/session/gen_domains.py from the files present (sorted), so adding a domain or an
 * opcode never edits a shared list. Two rows for one (opcode, sub) become duplicate `case`
 * labels in dispatch.c and fail compilation.
 */
#ifndef MU_SESSION_INTERNAL_H
#define MU_SESSION_INTERNAL_H

#include "mu_session.h"
#include "../net/mu_conn.h"

/* ---- dispatcher rows ---------------------------------------------------------------------
 *
 * In native/net/dispatch.def (generated from the binary, see that file):
 *   MU_FAMILY(opcode, sub_at_c1, sub_at_c2, client_subdispatch)
 *       the opcode is sub-dispatched by one byte, read where the client's own sub-dispatcher
 *       reads it for a 1-byte-size head (C1/C3) and a 2-byte-size head (C2/C4): F1 [3] via
 *       0x0128b24d, F4 [4] via 0x012883f0; "sub = packet[3] of a C1 head / [4] of C2"
 *       (reconstructed/skill/tree4.h:246). MU_AT_UNKNOWN: that head is not recovered for this
 *       family; such a frame is journaled as unbound, never guessed.
 *   MU_ROUTE(opcode, sub, client_handler, evidence)
 *       sub = MU_SUB_NONE for an opcode without a family row
 *
 * In native/session/ops/<domain>.ops (hand-written, one file per domain):
 *   MU_OP(opcode, sub, apply_fn)          binds a native apply function to one route
 *   MU_SUBMIT(intent_kind, submit_fn)     the domain that turns this intent kind into requests
 *
 * The client's own handler address, in dispatch.def only, is the single source of truth for
 * routing; an ops row only names which session function stands for a route. A domain author
 * cannot restate (and so cannot mistype) an address or a sub offset.
 */
#define MU_SUB_NONE 0x100u
#define MU_SUB_SHORT 0x101u      /* the frame is too short to carry its sub byte */
#define MU_SUB_HEAD 0x102u       /* the family's sub offset for this head is MU_AT_UNKNOWN */
#define MU_AT_UNKNOWN 0xffffu
#define MU_ADDR_UNVERIFIED 0u    /* dispatch.def: a route whose client handler address is not recovered yet */
#define MU_OP_KEY(op, sub) (((uint32_t)(op) << 9) | (uint32_t)(sub))

typedef enum mu_apply {
    MU_APPLY_DONE = 0,           /* state written (revisions bumped by the apply function) */
    MU_APPLY_IGNORED,            /* the client's handler ignores it (unknown key, dead character, ...) */
    MU_APPLY_WORLD_CHANGE        /* applied; the world changes: stop applying until attach_world(world) */
} mu_apply;

typedef mu_apply (*mu_apply_fn)(mu_session *s, const mu_frame *f);
typedef mu_submit (*mu_submit_fn)(mu_session *s, const mu_intent *in);

/* ---- the cue ring ------------------------------------------------------------------------- */
#define MU_CUE_RING 1024
typedef struct mu_cue_ring {
    mu_cue ring[MU_CUE_RING];
    uint64_t next_seq;           /* seq of the next cue written; ring[seq % MU_CUE_RING] */
} mu_cue_ring;

/* ---- held frames (world-change barrier) --------------------------------------------------- */
#define MU_HELD_FRAMES 512       /* TODO(NET-DISPATCH-001): the client's packet queue 0x01291777 capacity and its overflow rule */
typedef struct mu_held {
    mu_frame *frames;            /* heap, MU_HELD_FRAMES */
    uint32_t head, count;
} mu_held;

/* Domain state structs and the generated domain list:
 *   #define MU_DOMAIN(name) ...   one row per domains/<name>_state.h */
#include "session_domains_state.h"   /* generated: #include "domains/<d>_state.h" for each domain */

struct mu_session {
    mu_session_config cfg;
    mu_net net;
    mu_phase phase;
    mu_close_reason reason;
    int32_t reason_code;
    uint32_t now, tick;
    int pumping;                 /* submit asserts !pumping; attach_world may apply held frames */

    /* world attachment and barrier */
    mu_world_port port;
    int has_port;
    int32_t waiting_world;       /* -1 none */
    mu_held held;

    /* lease */
    uint32_t sim_epoch;
    int sim_open;

    /* outputs */
    uint32_t rev[MU_DOMAIN_COUNT];
    mu_cue_ring cues;
    uint32_t frames_in, frames_out, unhandled;

    /* one field per domain, generated: mu_dom_account account; mu_dom_hero hero; ... */
#define MU_DOMAIN(name) mu_dom_##name name;
#include "domains_all.def"
#undef MU_DOMAIN
};

/* ---- services for domain files ----------------------------------------------------------- */

/* Bump a domain's revision (call once per apply that changed it). */
void mu_session_touch(mu_session *s, mu_domain d);
/* Append a cue (seq assigned here). */
void mu_session_cue(mu_session *s, const mu_cue *cue);
/* Send a request on the connection the phase implies (game server once hopped). */
int mu_session_send(mu_session *s, mu_packet *p, int encrypted);
/* Phase transitions are only made through this (it bumps MU_DOMAIN_ACCOUNT and journals). */
void mu_session_set_phase(mu_session *s, mu_phase phase);
/* The hero's live motion through the port (the no-world answer without one). */
void mu_session_hero_motion(const mu_session *s, int32_t tile[2], float position[3], float angle[3]);
/* The session's world-port-backed mu_rp_env (players/monsters handlers at apply time). */
struct mu_rp_env;
void mu_session_rp_env(mu_session *s, struct mu_rp_env *env);
/* An unfinished request body: journal it, return MU_SUBMIT_UNRECOVERED. */
mu_submit mu_session_unrecovered(mu_session *s, const mu_intent *in, const char *what);

/* dispatch.c */
mu_apply mu_session_dispatch(mu_session *s, const mu_frame *f);
/* The routing table as data, for validate_dispatch.py (via a tiny CLI in native/tools/mu_session.c). */
typedef struct mu_dispatch_row { uint8_t opcode; uint16_t sub; uint32_t client_handler; const char *apply; } mu_dispatch_row;
size_t mu_session_dispatch_rows(const mu_dispatch_row **rows);

#endif /* MU_SESSION_INTERNAL_H */

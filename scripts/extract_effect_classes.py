#!/usr/bin/env python3
"""Extract the creation of the server classes whose CreateMonster case calls the
EffectManager (NATIVE-WORLD-002).

The NATIVE-ACTOR-001 class extraction (scripts/validate_actors.py) stops these
classes at the EffectManager singleton getter 0x00aee554. This script reruns
the same extraction (same machine, map-processor chain, regions and stubs)
with the effect calls of the case blocks replaced by recording stubs:

* 0x00aee554 EffectManager singleton getter -> a fake manager;
* 0x00a797a0 EffectManager::Create (thiscall, ret 0x30): records the effect
  path (the std::string stub keeps the literal pointer), position, rotation,
  scale, template-transform flag, tint flag and start frame, and writes a
  non-null shared pointer into the out slot;
* 0x0095e433 std::set default constructor (the action list passed by value)
  and 0x00965b01 shared_ptr destructor: no-ops;
* 0x0129f9c6 attach (thiscall on the object, ret 0x14): records the bone,
  follow-bone flag, timed flag and lifetime.

The vec3 constructor 0x0098a0e5, the no-op destructor 0x0095eda9 and the
shared_ptr test 0x00a78918 run as client code. The result is the class row
(model, opened NPC/monster, scale, slots) plus its effect attachments.
"""
import argparse
import json
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import actor_machine as am  # noqa: E402
import validate_actors as va  # noqa: E402

EFFECT_MANAGER, CREATE, SET_CTOR, SHARED_DTOR, ATTACH = 0x00aee554, 0x00a797a0, 0x0095e433, 0x00965b01, 0x0129f9c6
FAKE_EFFECT_MANAGER, FAKE_EFFECT, FAKE_CONTROL = 0x24000000, 0x24100000, 0x24200000
CLASSES = (750, 751, 752, 753, 758, 838, 873, 925)


def floats(m, address, count=3):
    return list(struct.unpack('<%df' % count, bytes(m.uc.mem_read(address, 4*count))))


def effect_stubs(record):
    def create(m):
        out, name = m.argument(0), m.argument(1)
        position, rotation = m.argument(2), m.argument(3)
        entry = {'path': m.cstring(m.read32(name)), 'position': floats(m, position), 'rotation': floats(m, rotation),
                 'scale': am.from_bits(m.argument(4)), 'template_transform': m.argument(5) & 0xff,
                 'tint': m.argument(7) & 0xff, 'start_frame': am.from_bits(m.argument(11))}
        record['effects'].append(entry)
        m.uc.mem_write(out, struct.pack('<II', FAKE_EFFECT+len(record['effects']), FAKE_CONTROL))
        return out, 0x30

    def attach(m):
        this = m.uc.reg_read(m.x86.UC_X86_REG_ECX)
        effect = m.read32(m.argument(0))
        record['attach'].append({'object': this, 'effect': effect-FAKE_EFFECT-1, 'bone': m.argument(1),
                                 'follow_bone': m.argument(2) & 0xff, 'timed': m.argument(3) & 0xff,
                                 'lifetime': am.from_bits(m.argument(4))})
        return 0, 0x14

    return {EFFECT_MANAGER: lambda m: FAKE_EFFECT_MANAGER, CREATE: create, ATTACH: attach,
            SET_CTOR: lambda m: (m.uc.reg_read(m.x86.UC_X86_REG_ECX), 0), SHARED_DTOR: lambda m: (0, 0)}


def extract(machine, server_class):
    captured = {}
    original = va.class_case

    def class_case(world, rand):
        regions, stubs, record = original(world, rand)
        record['effects'], record['attach'] = [], []
        stubs.update(effect_stubs(record))
        captured['record'] = record
        return regions, stubs, record

    va.class_case = class_case
    try:
        row = va.extract_class(machine, server_class)
    finally:
        va.class_case = original
    record = captured.get('record', {'effects': [], 'attach': []})
    row['effects'] = record['effects']
    row['attach'] = record['attach']
    if 'scale_bits' in row:
        row['scale'] = am.from_bits(row['scale_bits']) if row['scale_bits'] else va.DEFAULT_SCALE
    return row


def float_bits(value):
    return struct.unpack('<I', struct.pack('<f', value))[0]


def c_float(value):
    return f'{value!r}f' if value != int(value) else f'{value:.1f}f'


def emit_c(rows):
    lines = ['/* Generated by scripts/extract_effect_classes.py from the client\'s CreateMonster 0x0137fbac',
             ' * executed under Unicorn (world 0, rand() = 0) with the EffectManager factory 0x00a797a0 and the',
             ' * attach 0x0129f9c6 recorded by stubs (see docs/research/native-world-alive.md). Rows: server',
             ' * class, model index passed to CreateCharacter, opened NPC index, object scale; then the effects',
             ' * the case creates and attaches to the object, in call order. Do not edit. */',
             '#ifndef MU_EFFECT_CLASS_TABLE_H', '#define MU_EFFECT_CLASS_TABLE_H', '', '#include <stdint.h>', '',
             'typedef struct mu_effect_class_attach {',
             '    const char *path;          /* factory name (client path) */',
             '    float position[3], rotation[3], scale;',
             '    uint8_t template_transform, tint;',
             '    float start_frame;',
             '    int32_t bone;              /* attach 0x0129f9c6 arguments */',
             '    uint8_t follow_bone, timed;',
             '    float lifetime;',
             '} mu_effect_class_attach;', '',
             'typedef struct mu_effect_class {',
             '    uint32_t server_class, model;',
             '    int32_t npc_index;         /* OpenNpc index, -1 when none */',
             '    float scale;               /* object +0xa0 */',
             '    uint32_t first, count;     /* rows of mu_effect_class_attaches */',
             '} mu_effect_class;', '']
    classes, attaches = [], []
    for row in rows:
        if 'error' in row:
            continue
        npc = next((o[1] for o in row['opens'] if o[0] == 'npc'), -1)
        first = len(attaches)
        for effect, link in zip(row['effects'], row['attach']):
            if link['effect'] != len(attaches)-first:
                raise SystemExit(f"class {row['class']}: attach order differs from creation order")
            p, r = effect['position'], effect['rotation']
            path = effect['path'].replace('\\', '\\\\')
            attaches.append(f'    {{"{path}", {{{", ".join(c_float(v) for v in p)}}}, '
                            f'{{{", ".join(c_float(v) for v in r)}}}, {c_float(effect["scale"])}, '
                            f'{effect["template_transform"]}, {effect["tint"]}, {c_float(effect["start_frame"])}, '
                            f'{link["bone"]}, {link["follow_bone"]}, {link["timed"]}, {c_float(link["lifetime"])}}},')
        classes.append(f"    {{{row['class']}, 0x{row['model']:04x}, {npc if npc < 0 else hex(npc)}, {c_float(row['scale'])}, {first}, "
                       f"{len(attaches)-first}}},")
    lines += [f'#define MU_EFFECT_CLASS_ROWS {len(classes)}', f'#define MU_EFFECT_CLASS_ATTACHES {len(attaches)}', '',
              'static const mu_effect_class_attach mu_effect_class_attaches[MU_EFFECT_CLASS_ATTACHES] = {',
              *attaches, '};', '', 'static const mu_effect_class mu_effect_classes[MU_EFFECT_CLASS_ROWS] = {',
              *classes, '};', '', '#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--text', required=True)
    parser.add_argument('--data', required=True)
    parser.add_argument('--classes', default=','.join(str(c) for c in CLASSES))
    parser.add_argument('--output')
    parser.add_argument('--emit-c')
    args = parser.parse_args()
    text = am.load_pinned(args.text, am.TEXT_BYTES, am.TEXT_SHA256, 'restored text')
    data = am.load_pinned(args.data, am.DATA_BYTES, am.DATA_SHA256, 'second image section')
    machine = am.ActorMachine(text, data)
    rows = [extract(machine, int(c, 0)) for c in args.classes.split(',')]
    report = {'text_sha256': am.TEXT_SHA256, 'data_sha256': am.DATA_SHA256,
              'create_monster': va.BODIES['create_monster'][2], 'rows': rows}
    out = json.dumps(report, indent=1)
    if args.output:
        Path(args.output).write_text(out)
    if args.emit_c:
        Path(args.emit_c).write_text(emit_c(rows))
    for row in rows:
        if 'error' in row:
            print(row['class'], 'stopped:', row['error'])
            continue
        print(row['class'], 'model', hex(row['model'] or 0), 'opens', row['opens'], 'scale', round(row['scale'], 4))
        for effect, link in zip(row['effects'], row['attach'] + [None]*len(row['effects'])):
            print('   ', effect, link)
    # 838 and 925 read a per-monster effect list kept in an uncaptured static (0x0bdcfc10); they are
    # reported as stopped and left out of the table.
    return 0 if any('error' not in r for r in rows) else 1


if __name__ == '__main__':
    sys.exit(main())

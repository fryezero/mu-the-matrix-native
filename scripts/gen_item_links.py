#!/usr/bin/env python3
"""Generate reviewed sprite-chain parameters, checked against pinned link callers.

These are rendering rules, not model data. The independent ranked validator
varies random consumption, hand/link mode and clock after recipe selection.
"""
import argparse
from pathlib import Path
import pins
from validate_item_ranked import original_link
import validate_renderchar as v

ROOT = Path(__file__).resolve().parents[1]
# type, first bone, count, local Z, RGB multipliers, conditional grey flash,
# final white flare. Static sites: 0x012cb556 and 0x012cb7ab.
ROWS = [(0x0af9, 2, 7, 0, (1, 0.3, 0.1), 1, 0),
        (0x12f9, 1, 5, 10, (0.5, 0.5, 0.8), 0, 1)]


def generate():
    wa = tuple(p.read() for p in (pins.TEXT, pins.DATA, pins.FLAG, pins.FEATURE))
    f = lambda x: v.u2f(v.f2u(x))
    for t, first, count, z, rgb, flash, white in ROWS:
        for value in (0, 1, 2, 3, 29, 32767):
            _, calls, consumed = original_link(wa, t, [value]*32, 123.0)
            intensity = f((value % 30 + 70)*f(0.005))
            expected = []
            for i in range(count):
                bone = first + i
                offset = (0, 0, v.f2u(z))
                light = tuple(v.f2u(f(intensity*f(x))) for x in rgb)
                if flash and value % 3 == 0:
                    expected.append((0x7f67, bone, offset, v.f2u(0.6), (v.f2u(0.4),)*3,
                                     v.f2u(value % 360), 0, 4, 0))
                if not flash:
                    expected.append((0x7f67, bone, offset, v.f2u(1), light, 0, 0, 4, 0))
                if white and i == count-1:
                    light = (v.f2u(1),)*3
                expected.append((0x7ef7, bone, offset, v.f2u(2), light, 0, 0, 4, 0))
            if calls != expected or consumed != 1 + (count*(1 + (value % 3 == 0)) if flash else 0):
                raise AssertionError(('chain recipe does not fit', hex(t), value, calls, expected, consumed))
    lines = ['/* Generated by scripts/gen_item_links.py. Reviewed rendering parameters only. */',
             'typedef struct { int32_t type, first, count; float z, rgb[3]; int flash, white; } mu_rc_link_chain;',
             'static const mu_rc_link_chain mu_rc_link_chains[] = {']
    for t, first, count, z, rgb, flash, white in ROWS:
        floats = ', '.join(f'{x:.8f}f' for x in rgb)
        lines.append(f'    {{0x{t:04x}, {first}, {count}, {z:.1f}f, {{{floats}}}, {flash}, {white}}},')
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    result = generate()
    if a.check:
        if a.output.read_text() != result:
            raise SystemExit('link parameters drifted')
    else:
        a.output.write_text(result)

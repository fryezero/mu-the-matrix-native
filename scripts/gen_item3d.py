#!/usr/bin/env python3
"""Recover constant RenderItem3D overrides from the pinned restored instructions.

Only the data-like chain 0x016c168a..0x016c222d is interpreted. The time and
NewUI branches remain authored logic in item_slots.c. No client bytes are emitted.
Unknown instructions or calls fail closed; the external jump is never followed.
"""
import argparse
from pathlib import Path
import struct

import pins

START, END = 0x016c168a, 0x016c222d
CODES = (0x103b, 0x103c, 0x103d, 0x1049, 0x1053, 0x1088,
         0x1a0b, 0x1a0e, 0x1a13, 0x1a14, 0x1c09, 0x1c0b, 0x1c0c,
         0x1c15, 0x1c17, 0x1c18, 0x1c20, 0x1c21, 0x1c22, 0x1c2e, 0x1c2f, 0x1c30)
# Bit order: model, fx, fy, angle x/y/z, scale, level word.
FIELDS = ('[ebp - 0x14]', '[ebp - 0x20]', '[ebp - 0x1c]',
          'angle0', 'angle1', 'angle2', '[ebp - 0x18]', '[ebp + 0x1c]')


def overrides(insns, data, code, level):
    state = {'[ebp + 0x18]': code, '[ebp - 0x24]': level,
             '[ebp - 0x14]': code + 0xae6, '[ebp + 0x1c]': level * 8}
    original = dict(state)
    for key in FIELDS:
        state.setdefault(key, None)
    pc, cmp, arg = START, 0, None

    def read(op):
        if op.startswith(('dword ptr ', 'byte ptr ')):
            op = op.split('ptr ')[1]
        if op.startswith('[0x'):
            addr = int(op[1:-1], 16)
            return struct.unpack_from('<f', data, addr - 0x1a7c000)[0]
        if op in state:
            return state[op]
        return int(op, 0)

    def write(op, value):
        op = op.replace('dword ptr ', '')
        if op == '[eax]':
            op = state['eax']
        state[op] = value

    for _ in range(400):
        if pc == END:
            break
        ins = insns[pc]
        op, args = ins.mnemonic, ins.op_str.split(', ')
        nxt = pc + ins.size
        if op == 'cmp':
            cmp = read(args[0]) - read(args[1])
        elif op in ('jne', 'je', 'jg', 'jl', 'jmp'):
            take = {'jne': cmp != 0, 'je': cmp == 0, 'jg': cmp > 0,
                    'jl': cmp < 0, 'jmp': True}[op]
            if take:
                nxt = int(args[0], 16)
                if not START <= nxt <= END:
                    assert pc == 0x16c1afc and code == 0x1c0b and level > 7
                    return None
        elif op in ('mov', 'movss'):
            write(args[0], read(args[1]))
        elif op == 'xorps' and args == ['xmm0', 'xmm0']:
            state['xmm0'] = 0.0
        elif op == 'push':
            arg = read(args[0])
        elif op == 'call' and args == ['0xcfc922']:
            assert state['ecx'] == 0xb5e3c2c and arg in (0, 1, 2)
            state['eax'] = f'angle{arg}'
        elif op == 'or' and args == ['dword ptr [ebp + 0x1c]', '0xffffffff']:
            state['[ebp + 0x1c]'] = -1
        else:
            raise ValueError(f'unsupported instruction {pc:#x}: {op} {ins.op_str}')
        pc = nxt
    else:
        raise ValueError('chain did not terminate')
    mask, values = 0, []
    for bit, key in enumerate(FIELDS):
        changed = state[key] is not None and state[key] != original.get(key)
        mask |= int(changed) << bit
        values.append(state[key] if changed else 0)
    return mask, tuple(values)


def generate(text, data):
    from capstone import Cs, CS_ARCH_X86, CS_MODE_32
    # Decode through the patched span byte by byte: its tail is not an instruction.
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    insns = {}
    for pc in range(START, END):
        ins = next(md.disasm(text[pc-0x401000:pc-0x401000+16], pc, count=1), None)
        if ins:
            insns[pc] = ins
    rows = []
    for code in CODES:
        outcomes = [overrides(insns, data, code, level) for level in range(-1, 17)]
        if all(v == outcomes[0] for v in outcomes):
            groups = [(-1, outcomes[0])]
        else:
            groups = list(enumerate(outcomes[1:17]))
        for level, result in groups:
            if result is None or not result[0]:
                continue
            mask, v = result
            floats = ', '.join(float(x).hex() + 'f' for x in v[1:7])
            rows.append(f'    {{0x{code:x}, {level}, 0x{mask:02x}, {v[0]}, {{{floats}}}, {v[7]}}},')
    return ('/* Generated by scripts/gen_item3d.py from pinned RenderItem3D instructions.\n'
            ' * level -1 = every signed level; other rows use level_word >> 3, without a mask.\n'
            ' * Box of Luck levels >7 cross 0x016c1afc and remain unsupported. */\n'
            '#ifndef MU_ITEM3D_OVERRIDES_H\n#define MU_ITEM3D_OVERRIDES_H\n'
            'static const struct item3d_override {\n'
            '    int32_t code, level;\n    uint32_t mask;\n    int32_t model;\n'
            '    float values[6]; /* fx, fy, angle x/y/z, scale */\n'
            '    int32_t level_word;\n} item3d_overrides[] = {\n' + '\n'.join(rows) +
            '\n};\n#endif\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output', type=Path, required=True)
    args = ap.parse_args()
    args.output.write_text(generate(pins.TEXT.read(), pins.DATA.read()))


if __name__ == '__main__':
    main()

"""Instruction-checked low-level item caller groups in RenderObjDraw.

The table describes only the nine callers at 0x017de4c2..0x017deb61.
Body recipes and native consumers retain their separate admission checks.
"""
import capstone
import struct

# Dispatch start, body start, next dispatch, members, optional SSE light factor,
# first spill local. A shared body is checked once, with every dispatch member.
GROUPS = (
    (0x017de4c2, 0x017de4d2, 0x017de5d9, (0x2518,), False, 0),
    (0x017de5d9, 0x017de5f5, 0x017de6fc, (0x2710, 0x250c), False, 0),
    (0x017de6fc, 0x017de718, 0x017de873, (0x2511, 0x2543), True, 0x1510),
    (0x017de873, 0x017de89b, 0x017de9f6, (0x2512, 0x2544, 0x255a), True, 0x151c),
    (0x017de9f6, 0x017dea06, 0x017deb61, (0x2513,), True, 0x1528),
)
TYPES = tuple(sorted(t for *_, members, scale, spill in GROUPS for t in members))


def body_program(scale, spill):
    """Exact reviewed setter and ordered body/colour calls; no ignored opcodes."""
    out = []
    def add(source):
        out.extend(line.strip() for line in source.strip().splitlines())
    for channel in range(3):
        reg = 'eax' if scale else 'esi'
        pop = 'eax' if channel == 0 else reg
        add(f'push 4\npop {pop}')
        add(f'imul {reg}, eax, 0' if channel == 0 else f'shl {reg}, {channel - 1}')
        add(f'add {reg}, dword ptr [ebp + 0x10]')
        if scale:
            add('movss xmm0, dword ptr [eax]\nmulss xmm0, dword ptr [0x1a7edac]')
        add(f'push {channel}\nmov ecx, dword ptr [ebp - 0xb0]\nadd ecx, 0x54')
        if scale:
            local = spill + 4 * channel
            add(f'movss dword ptr [ebp - {local:#x}], xmm0\ncall 0xcfc922\nmovss xmm0, dword ptr [ebp - {local:#x}]\nmovss dword ptr [eax], xmm0')
        else:
            add('call 0xcfc922\nmov ecx, dword ptr [esi]\nmov dword ptr [eax], ecx')
    add('''push -1
push 3
push dword ptr [ebp + 0x30]
push dword ptr [ebp + 0x2c]
push dword ptr [ebp + 0x28]
push ecx
movss xmm0, dword ptr [ebp + 0x14]
movss dword ptr [esp], xmm0
push dword ptr [ebp + 0xc]
push dword ptr [ebp + 8]
push dword ptr [ebp - 0xb0]
call 0x16e036c
add esp, 0x24''')
    for flag, constant in ((0x240, 0x1a7e470), (0x1040, 0x1a7dd48)):
        add(f'''push -1
push ecx
movss xmm0, dword ptr [{constant:#x}]
movss dword ptr [esp], xmm0
mov eax, dword ptr [ebp + 0x28]
and eax, 0x100
or eax, {flag:#x}
push eax
push ecx
movss xmm0, dword ptr [{constant:#x}]
movss dword ptr [esp], xmm0
push dword ptr [ebp + 0xc]
push dword ptr [ebp + 8]
push dword ptr [ebp - 0xb0]
call 0x16dec15
add esp, 0x1c''')
    add('jmp 0x17e16fa')
    return out


def read(wa):
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    def check(start, end, expected):
        raw = wa[0][start - 0x401000:end - 0x401000]
        decoded = list(md.disasm(raw, start))
        actual = [f'{i.mnemonic} {i.op_str}' for i in decoded]
        if sum(i.size for i in decoded) != len(raw) or actual != expected:
            raise ValueError(f'unreviewed item caller instructions at {start:#x}')
    check(0x017de3e4, 0x017de3fd, [
        'cmp dword ptr [ebp - 0xa8], 3', 'jl 0x17de3fd',
        'mov eax, dword ptr [ebp + 8]', 'cmp dword ptr [eax + 0x5c], 0x26f5', 'jne 0x17e16ff'])
    result = {}
    for start, body, end, members, scale, spill in GROUPS:
        expected = []
        for index, t in enumerate(members):
            expected += ['mov eax, dword ptr [ebp + 8]', f'cmp dword ptr [eax + 0x5c], {t:#x}',
                         f'je {body:#x}' if index < len(members) - 1 else f'jne {end:#x}']
        check(start, body, expected)
        check(body, end, body_program(scale, spill))
        for t in members:
            result[t] = 0x3f666666 if scale else 0x3f800000
    for address, word in ((0x1a7e470, 0x3fc00000), (0x1a7dd48, 0x3f800000), (0x1a7edac, 0x3f666666)):
        if struct.unpack_from('<I', wa[1], address - 0x1a7c000)[0] != word:
            raise ValueError(f'unreviewed item caller constant at {address:#x}')
    return result


def render(rows):
    return ('/* Generated by item_caller_groups.read; RenderObjDraw low-level callers. */\n'
            'static const struct { int32_t type; float light; } mu_rc_low_callers[] = {\n' +
            ''.join(f'    {{0x{t:04x}, {"0.9f" if word == 0x3f666666 else "1.0f"}}},\n' for t, word in sorted(rows.items())) + '};\n')


def main():
    import argparse
    from pathlib import Path
    import pins
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render(read(tuple(p.read() for p in (pins.TEXT, pins.DATA))))
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit('item caller groups differ from pinned instructions')
    else:
        args.output.write_text(result)


if __name__ == '__main__':
    main()

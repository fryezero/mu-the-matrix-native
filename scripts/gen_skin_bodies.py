#!/usr/bin/env python3
"""Generate the class-skin early-return draw recipes from pinned instructions.

Only the reviewed raw-level and effective-level branches below use this table. Other levels retain
RenderObjDraw's normal scalar/glow path. Full-function comparisons are separate.
"""
import argparse
from pathlib import Path
import random
import gen_item_bodies as gen
import pins
import validate_renderchar as v
from item_body_machine import ResetWorld

ROOT = Path(__file__).resolve().parents[1]
# First match wins, including the type's optional any-level fallback.
BRANCHES = ((0x3895, 14, 0), (0x3895, 15, 0), (0x3896, 13, 1), (0x389b, 1, 1), (0x389b, -1, 0), (0x389e, 9, 1))


def generate():
    wa = tuple(pin.read() for pin in (pins.TEXT, pins.DATA, pins.FLAG, pins.FEATURE))
    reset = ResetWorld(wa)
    rows = []
    for t, level, effective in BRANCHES:
        samples = []
        for seed in range(60):
            case = v.random_case_any(random.Random(0x2002e + seed), t)
            raw_level = 2 if effective and t in (0x389b, 0x389e) else max(level, 0)
            case.update(item_level=(raw_level << 3) | (seed % 8), quality=9,
                        render_type=(2, 0x102, 0x40042)[seed % 3],
                        record=(0, 0, 0), a10=0xffffffff, a11=0xffffffff)
            result, stream, other, _ = v.client_stream(wa, case, reset)
            if not result['ok'] or other:
                raise ValueError(('skin branch unavailable', hex(t), level))
            raw = [case['render_type'], case['alpha'], case['blend_mesh'], case['blend_light'],
                   case['u'], case['v'], 0, 0xffffffff, *case['model_light'], case['model_level'],
                   *case['model_shade'], case['model_ca'], case['object_alpha']]
            samples.append((raw, [(d[0], gen.flat(d)) for d in stream]))
        rule = gen.infer(samples)
        if rule is None:
            raise ValueError(('skin branch no longer fits', hex(t), level))
        rows.append((t, level, effective, rule))
    lines = ['/* Generated by scripts/gen_skin_bodies.py. Early-return rendering rules; effective=0 selects raw level, 1 selects capped glow level. */',
             'static const struct { int32_t type, level, effective; mu_rc_body_recipe recipe; } mu_rc_skin_bodies[] = {']
    for t, level, effective, rule in rows:
        lines.append('    {0x%04x, %d, %d, {%d, {' % (t, level, effective, len(rule)))
        for entry, cells in rule:
            sources = ', '.join(str(value + 1 if op == 'in' else 0) for op, value in cells)
            values = ', '.join('0' if op == 'in' else '0x%08xu' % (value & 0xffffffff) for op, value in cells)
            lines.append('        {%d, {%s}, {%s}},' % (1 if entry == 'BODY' else 2, sources, values))
        lines.append('    }}},')
    return '\n'.join(lines + ['};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = generate()
    if args.check:
        if args.output.read_text() != value:
            raise SystemExit('skin body recipes differ')
    else:
        args.output.write_text(value)


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Extract RenderObjDraw's closed type/level remap chain from pinned instructions.

Only authored scalar rules leave the capture: one 16-level lookup per changed
model type. No engine calls or generated client instruction bytes are emitted.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pins

START, END = 0x0176d160, 0x0176dc26
SKIN_TYPES = [0x3700, 0x3890, 0x3891, *range(0x3894, 0x38a1), 0x38a2]


def generate(text, types=range(0xae6, 0x2ae6), symbol="mu_rc_glow_rows"):
    from unicorn import Uc, UC_ARCH_X86, UC_MODE_32
    from unicorn.x86_const import UC_X86_REG_EBP
    import struct
    uc = Uc(UC_ARCH_X86, UC_MODE_32)
    uc.mem_map(0x401000, (len(text) + 4095) & ~4095)
    uc.mem_write(0x401000, text)
    uc.mem_map(0x20000000, 0x2000)
    bp = 0x20001000
    uc.reg_write(UC_X86_REG_EBP, bp)
    rows = []
    for t in types:
        levels = []
        uc.mem_write(bp + 0xc, struct.pack('<i', t))
        for level in range(16):
            uc.mem_write(bp - 0xa8, struct.pack('<i', level))
            uc.emu_start(START, END, count=256)
            # Reaching END is mandatory, including indirect switch tables.
            from unicorn.x86_const import UC_X86_REG_EIP
            if uc.reg_read(UC_X86_REG_EIP) != END:
                raise ValueError(f'unclosed remap at {t:#x}/{level}')
            levels.append(struct.unpack('<i', uc.mem_read(bp - 0xa8, 4))[0])
        if levels != list(range(16)):
            rows.append((t, levels))
    lines = ['/* Generated by scripts/gen_item_glow.py from pinned RenderObjDraw',
             ' * 0x0176d160..0x0176dc26. Scalar type/level rules only. */',
             'static const struct { int32_t type; int8_t levels[16]; } '+symbol+'[] = {']
    lines += ['    {0x%04x, {%s}},' % (t, ', '.join(map(str, ls))) for t, ls in rows]
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--skins', action='store_true', help='generate the separate class-skin scalar rules')
    args = parser.parse_args()
    text = pins.TEXT.read()
    result = generate(text, SKIN_TYPES, 'mu_rc_skin_glow_rows') if args.skins else generate(text)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit('item glow table differs from pinned instructions')
    else:
        args.output.write_text(result)


if __name__ == '__main__':
    main()

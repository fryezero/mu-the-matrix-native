#!/usr/bin/env python3
"""Generate scalar sprite recipes for link targets 0x012cca07, 0x012cbb43, 0x012cbd11.

Parameters are reviewed rendering rules. Pinned caller comparisons reject drift;
validate_item_gear.py independently varies clocks, hands and random sequences.
"""
import argparse
from pathlib import Path
import math
import pins
import validate_renderchar as v
from validate_item_ranked import original_link

ROOT = Path(__file__).resolve().parents[1]
# A scalar expression is source, multiplier, addend. Source zero is constant.
def const(value): return (0, 0, value)
def expr(source, mul=1, add=0): return (source, mul, add)

def rules():
    rows = {}
    rows[0x0afa] = [(bone, 0x7ef7, (0,0,0), scale, rgb, const(0))
                    for bone in (1,2)
                    for scale,rgb in ((expr(2,0.9), (expr(2,0.43),expr(2,0.14),expr(2,0.6))),
                                      (expr(3,0.5,0.4), (const(0.3),)*3))]
    rows[0x0eed] = [(1,0x7ef7,(0,0,0),const(2),(expr(1),expr(1,0.9),const(0)),const(0)),
                    (1,0x7ef7,(0,0,0),expr(3,1,0.5),(const(0.5),)*3,const(0))]
    rows[0x0eee] = [(1,0x7ef7,(x,0,0),expr(4,1,1),(expr(1,0.2),expr(1,0.1),expr(1,3)),const(0))
                    for x in (-15,10)] + [
                    (1,0x7f67,(10,0,0),const(0.6),(expr(6),)*3,expr(5,-1,360)),
                    (1,0x7f67,(10,0,0),const(0.6),(expr(6),)*3,expr(5))]
    rows[0x10f0] = [(bone,0x7ef7,(0,0,0),const(1.3),(expr(1,0.2),expr(1,0.1),expr(1,0.8)),const(0)) for bone in range(1,9)]
    rows[0x16f5] = [(1,bitmap,(15,-15,0),scale,(expr(1,0.6),expr(1,0.6),expr(1,2)),const(0))
                    for bitmap,scale in ((0x7f67,const(1.5)),(0x7ef7,expr(1,1,1.5)))]
    return rows

def expected(t, value, time):
    f = lambda x: v.u2f(v.f2u(x))
    sin2, sin1 = f(math.sin(f(time*f(0.002)))), f(math.sin(f(time*f(0.001))))
    scalars = (0,f((value%30+70)*f(0.005)), f(f(sin2*f(0.35))+f(0.65)),
               sin2,sin1,f(f(math.sin(f(time*f(0.01))))*360),f(f(sin1*f(0.5))+f(0.5)))
    def evaluate(e):
        source,mul,add=e
        if not source:return v.f2u(add)
        value=scalars[source] if mul==1 else f(scalars[source]*f(mul))
        return v.f2u(f(value+f(add)) if add else value)
    return [(bitmap,bone,tuple(map(v.f2u,offset)),evaluate(scale),tuple(map(evaluate,rgb)),evaluate(rotation),0,4,0)
            for bone,bitmap,offset,scale,rgb,rotation in rules()[t]]

def generate():
    wa=tuple(p.read() for p in (pins.TEXT,pins.DATA,pins.FLAG,pins.FEATURE))
    rows=rules()
    for t in rows:
        for value in (0,1,29,30,32767):
            for time in (0,500.25,-150.5,123456):
                _,calls,n=original_link(wa,t,[value]*32,time)
                if calls!=expected(t,value,time) or n!=1:
                    raise AssertionError(('pulse recipe drift',hex(t),value,time,calls,expected(t,value,time),n))
    lines=['/* Generated by scripts/gen_item_pulse_links.py. Rendering rules only. */',
           'typedef struct { uint8_t source; float mul, add; } mu_rc_link_scalar;',
           'typedef struct { int32_t bone, bitmap; float offset[3]; mu_rc_link_scalar scale, rgb[3], rotation; } mu_rc_pulse_sprite;',
           'static const mu_rc_pulse_sprite mu_rc_pulse_sprites[] = {']
    def scalar(e):return '{%d, %.9ff, %.9ff}'%e
    for sprites in rows.values():
        for bone,bitmap,offset,scale,rgb,rotation in sprites:
            lines.append('    {%d, 0x%x, {%s}, %s, {%s}, %s},' % (bone,bitmap,', '.join('%.1ff'%x for x in offset),scalar(scale),', '.join(map(scalar,rgb)),scalar(rotation)))
    lines+=['};','static const struct { int32_t type, first, count; } mu_rc_pulse_links[] = {']
    first=0
    for t,sprites in rows.items():
        lines.append('    {0x%04x, %d, %d},'%(t,first,len(sprites)));first+=len(sprites)
    return '\n'.join(lines+['};',''])

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path,required=True);p.add_argument('--check',action='store_true');a=p.parse_args()
    result=generate()
    if a.check:
        if a.output.read_text()!=result:raise SystemExit('pulse links drifted')
    else:a.output.write_text(result)
